/// Mean-centred lag covariance sums mirroring Python `autocorrelation_cpu` in
/// `control/autocorrelation/autocorrelation_acf.py`; lags `0..=max_lag`.
fn python_autocovariance_sum(data: &[f64], max_lag: usize) -> Vec<f64> {
    let n = data.len();
    let mean = data.iter().copied().sum::<f64>() / airspring_barracuda::cast::usize_f64(n);
    let max_lag = max_lag.min(n.saturating_sub(1));
    (0..=max_lag)
        .map(|lag| {
            (0..(n - lag))
                .map(|i| (data[i] - mean) * (data[i + lag] - mean))
                .sum()
        })
        .collect()
}

/// Python-control normalised ACF: `c_lag / c_0` (zero vector if `c_0 == 0`).
fn python_normalised_acf(data: &[f64], max_lag: usize) -> Vec<f64> {
    let raw = python_autocovariance_sum(data, max_lag);
    if raw.is_empty() || raw[0] == 0.0 {
        return vec![0.0; raw.len()];
    }
    let c0 = raw[0];
    raw.into_iter().map(|c| c / c0).collect()
}

/// Deterministic “white noise” series from the Python control (`sin` + `cos`, `n = 200`).
fn white_noise_series() -> Vec<f64> {
    (0..200)
        .map(|i| {
            let i = airspring_barracuda::cast::usize_f64(i);
            (0.7_f64 * i).sin() + (1.3_f64 * i).cos()
        })
        .collect()
}

