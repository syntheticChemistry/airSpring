fn f64_array(value: &Value, context: &str) -> Vec<f64> {
    value
        .as_array()
        .unwrap_or_else(|| panic!("{context}: expected JSON array"))
        .iter()
        .map(|v| {
            v.as_f64()
                .unwrap_or_else(|| panic!("{context}: expected f64"))
        })
        .collect()
}

fn validate_reference_parity(v: &mut ValidationHarness, bench: &Value) {
    validation::section("Python-definition ACF vs benchmark reference");
    let reference = &bench["reference"];
    let want_n = f64_array(
        &reference["normalised_acf_lags_0_20"],
        "normalised_acf_lags_0_20",
    );
    let want_r = f64_array(&reference["raw_acf_lags_0_20"], "raw_acf_lags_0_20");

    let nacf = python_normalised_acf(&AR1_SERIES, 20);
    let raw = python_autocovariance_sum(&AR1_SERIES, 20);
    assert_eq!(nacf.len(), want_n.len(), "normalised ACF length");
    assert_eq!(raw.len(), want_r.len(), "raw autocovariance length");

    for (i, (&c, &e)) in nacf.iter().zip(&want_n).enumerate() {
        v.check_abs(&format!("python_nacf lag {i}"), c, e, ACF_TOL);
    }
    for (i, (&c, &e)) in raw.iter().zip(&want_r).enumerate() {
        v.check_abs(&format!("python_raw_autocov lag {i}"), c, e, ACF_TOL);
    }

    let first10 = f64_array(&reference["ar1_data_first_10"], "ar1_data_first_10");
    for (i, (&a, &b)) in AR1_SERIES.iter().zip(&first10).enumerate() {
        v.check_abs(
            &format!("AR(1) series[{i}] vs benchmark first_10"),
            a,
            b,
            f64::EPSILON,
        );
    }
}

fn validate_barracuda_cpu(v: &mut ValidationHarness) {
    validation::section("Barracuda CPU autocorrelation (known-answer + AR(1) series)");
    let known = [1.0_f64, 2.0, 3.0, 4.0, 5.0];
    let acf = autocorrelation_cpu(&known, 3);
    v.check_abs("known C(0)", acf[0], 11.0, 1e-9);
    v.check_abs("known C(1)", acf[1], 10.0, 1e-9);
    let nacf = normalised_acf_cpu(&known, 3);
    v.check_abs("known nacf lag0", nacf[0], 1.0, 1e-12);

    let wn = white_noise_series();
    let nacf_w = normalised_acf_cpu(&wn, 11);
    v.check_abs("white_noise Rust nacf[0]", nacf_w[0], 1.0, 1e-12);

    let nacf_ar = normalised_acf_cpu(&AR1_SERIES, 21);
    v.check_bool(
        "Rust AR(1): nacf[1] in [0.5, 0.95]",
        (0.5..=0.95).contains(&nacf_ar[1]),
    );
    v.check_bool("Rust AR(1): nacf[1] > nacf[5]", nacf_ar[1] > nacf_ar[5]);
    let raw_ar = autocorrelation_cpu(&AR1_SERIES, 6);
    v.check_bool("Rust AR(1): raw C(0) > 0", raw_ar[0] > 0.0);

    let constant = vec![5.0_f64; 50];
    let nacf_c = normalised_acf_cpu(&constant, 4);
    for (lag, &val) in nacf_c.iter().enumerate().skip(1) {
        v.check_abs(
            &format!("Rust constant-series nacf lag {lag} (≠ Python definition)"),
            val,
            1.0,
            1e-12,
        );
    }
}

fn validate_benchmark_checks(v: &mut ValidationHarness, bench: &Value) {
    validation::section("Benchmark `checks` array (by name)");

    let checks = bench["checks"]
        .as_array()
        .expect("benchmark checks must be an array");

    for c in checks {
        let name = c["name"].as_str().expect("check name");

        match name {
            "white_noise_lag0" => {
                let nacf = normalised_acf_cpu(&white_noise_series(), 11);
                let computed = nacf[0];
                let expected = c["expected"].as_f64().expect("expected");
                let tol = c["tolerance"].as_f64().expect("tolerance");
                v.check_abs(name, computed, expected, tol);
            }
            "ar1_lag1_positive" => {
                let nacf = normalised_acf_cpu(&AR1_SERIES, 6);
                let computed = nacf[1];
                let lo = c["expected_range"][0].as_f64().expect("lo");
                let hi = c["expected_range"][1].as_f64().expect("hi");
                v.check_bool(
                    &format!("{name}: nacf[1]={computed:.6} in [{lo:.2}, {hi:.2}]"),
                    (lo..=hi).contains(&computed),
                );
            }
            "ar1_lag1_gt_lag5" => {
                let nacf = normalised_acf_cpu(&AR1_SERIES, 6);
                v.check_bool(name, nacf[1] > nacf[5]);
            }
            "constant_data_acf_zero" => {
                let constant = [5.0_f64; 50];
                let nacf = python_normalised_acf(&constant, 3);
                let expected = c["expected"].as_f64().expect("expected");
                let tol = c["tolerance"].as_f64().expect("tolerance");
                v.check_abs(name, nacf[1], expected, tol);
            }
            "raw_acf_lag0_positive" => {
                let raw = python_autocovariance_sum(&AR1_SERIES, 5);
                v.check_bool(name, raw[0] > 0.0);
            }
            other => panic!("unexpected benchmark check: {other}"),
        }
    }
}

fn main() {
    validation::init_tracing();
    validation::banner("Autocorrelation / ACF Validation");
    let mut v = ValidationHarness::new("Autocorrelation ACF");
    let Ok(bench) = parse_benchmark_json(BENCHMARK_JSON) else {
        eprintln!("[FAIL] benchmark JSON parse error");
        std::process::exit(1);
    };

    validate_reference_parity(&mut v, &bench);
    validate_barracuda_cpu(&mut v);
    validate_benchmark_checks(&mut v, &bench);

    v.finish();
}
