//! Validate autocorrelation (ACF / autocovariance) against Python baseline
//! (`control/autocorrelation/autocorrelation_acf.py`).
//!
//! The control script defines **mean-centred summed autocovariance** (lags 0..`max_lag`
//! inclusive) and divides by lag-0 variance to produce a normalised ACF. Barracuda’s
//! [`autocorrelation_cpu`]
//! uses averaged lag products without mean removal — semantics differ by design.
//! This binary reproduces the Python definition for parity with the benchmark JSON while
//! also exercising the Barracuda CPU helpers on the same deterministic AR(1) series.

use airspring_barracuda::gpu::autocorrelation::{autocorrelation_cpu, normalised_acf_cpu};
use airspring_barracuda::validation::{self, ValidationHarness, parse_benchmark_json};
use serde_json::Value;

